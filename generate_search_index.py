class Build:
    def __init__(self):
        self.category_pages = collections.defaultdict(list)   # cat -> [(fromTok, toTok)]
        self.unit_names = collections.defaultdict(collections.Counter)  # (cat,tok) -> Counter(name)
        self.unit_syms = collections.defaultdict(collections.Counter)
        self.explicit = []          # explicit page dicts (home, hubs, root conversions, static)
        self.skipped = []           # (url, reason) eligible-on-disk pages we deliberately do not index
        self.fallback_titles = []   # category pages whose title did not match the expected pattern
        self.name_conflicts = 0
        self.symbol_conflicts = 0


def classify(inv, site_dir: Path) -> Build:
    b = Build()
    cat_ids = set(CATEGORY_LABELS)
    for url in inv.urls:
        rel_src, _explicit = inv.sources.get(url, (None, False))
        path = url[len(BASE_URL):]  # begins with "/"
        if path == "/":
            seg = []
        else:
            seg = path.strip("/").split("/") if path.endswith("/") else [path.lstrip("/")]
        title_path = site_dir / rel_src if rel_src else None

        # home
        if path == "/":
            b.explicit.append({"kind": "page", "rel": "", "title": "Home", "category": "Home"})
            continue

        # root-level .html pages (guides, tools, about, ...)
        if not path.endswith("/") and len(seg) == 1 and seg[0].endswith(".html"):
            raw = read_title(title_path)
            title = clean_page_title(raw) or title_words(seg[0][:-5])
            cat = "Guides" if (seg[0].endswith("-guide.html") or " vs " in title.lower() or seg[0].startswith(("what-is", "guides", "metric-vs", "acre-vs", "celsius-vs"))) else "Tools"
            if seg[0] in ("about.html", "contact.html", "references.html", "sitemap.html", "privacy.html", "terms.html"):
                cat = "About"
            b.explicit.append({"kind": "page", "rel": seg[0], "title": title, "category": cat})
            continue

        if not path.endswith("/"):
            b.skipped.append((url, "non-directory-url"))
            continue

        # category hub  /speed/
        if len(seg) == 1 and seg[0] in cat_ids:
            b.explicit.append({"kind": "hub", "rel": seg[0] + "/", "title": CATEGORY_LABELS[seg[0]], "category": CATEGORY_LABELS[seg[0]], "cat": seg[0]})
            continue

        # popular root conversion  /kg-to-lbs/
        if len(seg) == 1 and "-to-" in seg[0]:
            slug = seg[0]
            parts = slug.split("-to-")
            if len(parts) != 2 or not all(SLUG_RE.match(p) for p in parts):
                b.skipped.append((url, "invalid-root-conversion-slug"))
                continue
            raw = read_title(title_path)
            b.explicit.append({"kind": "conv", "rel": slug + "/", "slug": slug, "from": parts[0], "to": parts[1], "rawTitle": raw})
            continue

        # category conversion page  /speed/knot-to-mile-per-hour/
        if len(seg) == 2 and seg[0] in cat_ids:
            cat, slug = seg
            parts = slug.split("-to-")
            if len(parts) != 2 or not all(SLUG_RE.match(p) for p in parts) or parts[0] == parts[1]:
                b.skipped.append((url, "invalid-conversion-slug"))
                continue
            raw = read_title(title_path)
            m = CONV_TITLE_RE.match(raw)
            names = syms = None
            if m:
                n = m.group(1).split(" to ")
                s = m.group(2).split(" to ")
                if len(n) == 2 and len(s) == 2:
                    names, syms = n, s
            if names is None:
                b.fallback_titles.append(url)
                names = [title_words(parts[0]), title_words(parts[1])]
                syms = ["", ""]
            for tok, nm, sy in ((parts[0], names[0], syms[0]), (parts[1], names[1], syms[1])):
                b.unit_names[(cat, tok)][nm] += 1
                b.unit_syms[(cat, tok)][sy] += 1
            b.category_pages[cat].append((parts[0], parts[1]))
            continue

        b.skipped.append((url, "unclassified-path"))
    return b


# --------------------------------------------------------------------------
# build the JSON documents
# --------------------------------------------------------------------------

def most_common(counter):
    return sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]


def build_documents(b: Build):
    # ---- units + pair bitmaps -------------------------------------------
    unit_rows = []        # categories array for units.json
    shards = {}           # cat -> shard dict
    cat_info = []
    name_conflicts = symbol_conflicts = 0
    for cat_id, label in NAV_CATEGORIES:
        pages = b.category_pages.get(cat_id)
        if not pages:
            continue
        toks = sorted({t for pair in pages for t in pair})
        index = {t: i for i, t in enumerate(toks)}
        units = []
        for t in toks:
            names = b.unit_names[(cat_id, t)]
            syms = b.unit_syms[(cat_id, t)]
            if len(names) > 1:
                name_conflicts += 1
            if len(syms) > 1:
                symbol_conflicts += 1
            aliases, kws, tier = curated_for_token(t)
            row = [t, most_common(names), most_common(syms), tier]
            if aliases or kws:
                row.append(aliases if aliases else 0)
            if kws:
                row.append(kws)
            units.append(row)
        n = len(toks)
        bits = bytearray((n * n + 7) // 8)
        seen = set()
        dup = 0
        for a, c in pages:
            if (a, c) in seen:
                dup += 1
                continue
            seen.add((a, c))
            k = index[a] * n + index[c]
            bits[k >> 3] |= 1 << (k & 7)
        if dup:
            raise IndexError_(f"{cat_id}: {dup} duplicate (from,to) pair(s) - two files resolve to one URL")
        unit_rows.append({"id": cat_id, "label": label, "u": units})
        shards[cat_id] = {"v": FORMAT_VERSION, "c": cat_id, "n": n, "p": len(seen), "b": base64.b64encode(bytes(bits)).decode("ascii")}
        cat_info.append({"id": cat_id, "label": label, "units": n, "pages": len(seen), "shard": f"pairs/{cat_id}.json"})
    b.name_conflicts, b.symbol_conflicts = name_conflicts, symbol_conflicts

    # ---- explicit pages ---------------------------------------------------
    pages_out = []
    seen_rel = set()
    for e in sorted(b.explicit, key=lambda x: (x["kind"], x["rel"])):
        if e["rel"] in seen_rel:
            raise IndexError_(f"duplicate explicit page url: {e['rel']!r}")
        seen_rel.add(e["rel"])
        if e["kind"] == "conv":
            m = CONV_TITLE_RE.match(e["rawTitle"])
            names = syms = None
            if m:
                n = m.group(1).split(" to ")
                s = m.group(2).split(" to ")
                if len(n) == 2 and len(s) == 2:
                    names, syms = n, s
            if names is None:
                plain = clean_page_title(e["rawTitle"]).split(" to ")
                names = plain if len(plain) == 2 else [title_words(e["from"]), title_words(e["to"])]
                syms = ["", ""]
            sides = []
            for tok, nm, sy in ((e["from"], names[0], syms[0]), (e["to"], names[1], syms[1])):
                aliases, kws, _tier = curated_for_token(tok)
                side = {"s": tok, "n": nm}
                if sy:
                    side["y"] = sy
                if aliases:
                    side["a"] = aliases
                if kws:
                    side["k"] = kws
                sides.append(side)
            pages_out.append({"t": f"{names[0]} to {names[1]}", "u": e["rel"], "c": "Popular", "f": sides[0], "o": sides[1], "x": "conv"})
        elif e["kind"] == "hub":
            pages_out.append({"t": e["title"], "u": e["rel"], "c": e["category"], "x": "hub",
                              "a": [e["title"].lower() + " converter"], "k": ["category", "conversions", "unit converter"]})
        else:
            kw = STATIC_PAGE_KEYWORDS.get(e["rel"], [])
            pages_out.append({"t": e["title"], "u": e["rel"], "c": e["category"], "x": "page", **({"k": kw} if kw else {})})

    units_doc = {"v": FORMAT_VERSION, "categories": unit_rows}
    pages_doc = {"v": FORMAT_VERSION, "pages": pages_out}
    return units_doc, pages_doc, shards, cat_info


def dump(obj) -> bytes:
    return (json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")


def expand_urls(units_doc, pages_doc, shards):
    """Re-derive every URL the index claims exists (used for verification and tests)."""
    urls = set()
    for cat in units_doc["categories"]:
        shard = shards[cat["id"]]
        n = shard["n"]
        data = base64.b64decode(shard["b"])
        toks = [u[0] for u in cat["u"]]
        for i in range(n):
            for j in range(n):
                k = i * n + j
                if (data[k >> 3] >> (k & 7)) & 1:
                    urls.add(f"/{cat['id']}/{toks[i]}-to-{toks[j]}/")
    for p in pages_doc["pages"]:
        urls.add("/" + p["u"])
    return urls


def write_index(out_dir: Path, units_doc, pages_doc, shards, cat_info, stats):
    files = {"units.json": dump(units_doc), "pages.json": dump(pages_doc)}
    for cat, shard in shards.items():
        files[f"pairs/{cat}.json"] = dump(shard)

    h = hashlib.sha256()
    for name in sorted(files):
        h.update(name.encode())
        h.update(files[name])
    version = h.hexdigest()[:12]

    sizes = {name: {"bytes": len(data), "gzip": len(gzip.compress(data, 9, mtime=0))} for name, data in sorted(files.items())}
    total_bytes = sum(s["bytes"] for s in sizes.values())
    total_gzip = sum(s["gzip"] for s in sizes.values())
    category_pages = sum(c["pages"] for c in cat_info)
    manifest = {
        "format": FORMAT_VERSION,
        "version": version,
        "files": {"units": "units.json", "pages": "pages.json"},
        "categories": cat_info,
        "totals": {
            "entries": category_pages + len(pages_doc["pages"]),
            "categoryPages": category_pages,
            "explicitPages": len(pages_doc["pages"]),
            "units": sum(len(c["u"]) for c in units_doc["categories"]),
            "bytes": total_bytes,
            "gzipBytes": total_gzip,
        },
        "sizes": sizes,
        "stats": stats,
    }
    files["manifest.json"] = dump(manifest)
    return files, manifest


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--site-dir", default=str(ROOT), help="published site root to scan (default: this folder)")
    ap.add_argument("--out-dir", default=None, help=f"output folder (default: <site-dir>/{OUT_DIR_NAME})")
    ap.add_argument("--orphan-canonicals", choices=["exclude", "include"], default="include",
                    help="pages whose canonical URL has no file: index them under the URL they are served at "
                         "(default) or exclude them")
    ap.add_argument("--check", action="store_true", help="do not write; fail if the files on disk are not current")
    args = ap.parse_args(argv)

    site_dir = Path(args.site_dir).resolve()
    out_dir = Path(args.out_dir).resolve() if args.out_dir else site_dir / OUT_DIR_NAME
    t0 = time.time()

    try:
        inv = gs.collect_inventory(site_dir, orphan_policy="exclude")
    except gs.SitemapError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    if not inv.urls:
        print("ERROR: no indexable pages found; refusing to write an empty search index.", file=sys.stderr)
        return 1

    # Optionally treat orphan-canonical pages as indexable under the URL they are actually served at.
    orphan_urls = []
    if args.orphan_canonicals == "include":
        urls = set(inv.urls)
        for target, sources in inv.orphans.items():
            for rel in sources:
                furl = gs.file_url(rel)
                urls.add(furl)
                inv.sources[furl] = (rel, False)
                orphan_urls.append(furl)
        inv.urls = sorted(urls)

    b = classify(inv, site_dir)
    units_doc, pages_doc, shards, cat_info = build_documents(b)

    # ---- verification: the index must expand to exactly the canonical pages on disk -------------
    claimed = expand_urls(units_doc, pages_doc, shards)
    on_disk = {u[len(BASE_URL):] for u in inv.urls}
    skipped = {u[len(BASE_URL):] for u, _ in b.skipped}
    missing = sorted(on_disk - claimed - skipped)
    phantom = sorted(claimed - on_disk)
    if phantom:
        print(f"ERROR: index lists {len(phantom)} URL(s) that are not published pages, e.g. {phantom[:5]}", file=sys.stderr)
        return 1
    if missing:
        print(f"ERROR: {len(missing)} published page(s) are missing from the index, e.g. {missing[:5]}", file=sys.stderr)
        return 1

    reasons = collections.Counter(r for _, r in b.skipped)
    stats = {
        "htmlFilesScanned": inv.html_files,
        "canonicalPagesOnDisk": len(on_disk),
        "excludedByReason": inv.excluded_by_reason(),
        "orphanCanonicalPages": sum(len(v) for v in inv.orphans.values()),
        "orphanCanonicalsIndexed": len(orphan_urls),
        "skippedUnclassified": dict(sorted(reasons.items())),
        "fallbackTitles": len(b.fallback_titles),
        "unitNameConflicts": b.name_conflicts,
        "unitSymbolConflicts": b.symbol_conflicts,
    }
    files, manifest = write_index(out_dir, units_doc, pages_doc, shards, cat_info, stats)

    if args.check:
        stale = []
        for name, data in files.items():
            p = out_dir / name
            if not p.exists() or p.read_bytes() != data:
                stale.append(name)
        extra = sorted(str(p.relative_to(out_dir)).replace("\\", "/") for p in out_dir.rglob("*.json")
                       if str(p.relative_to(out_dir)).replace("\\", "/") not in files) if out_dir.exists() else []
        if stale or extra:
            print(f"STALE: {len(stale)} file(s) differ, {len(extra)} unexpected: {(stale + extra)[:8]}", file=sys.stderr)
            return 1
        print(f"OK: {out_dir.relative_to(site_dir) if out_dir.is_relative_to(site_dir) else out_dir} is current "
              f"({manifest['totals']['entries']:,} entries).")
        return 0

    # write (only touch files that changed, remove files from a previous layout)
    (out_dir / "pairs").mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        p = out_dir / name
        if not p.exists() or p.read_bytes() != data:
            p.write_bytes(data)
    for p in list(out_dir.rglob("*.json")):
        rel = str(p.relative_to(out_dir)).replace("\\", "/")
        if rel not in files:
            p.unlink()

    t = manifest["totals"]
    if stats["orphanCanonicalPages"]:
        action = "indexed under their served URL" if args.orphan_canonicals == "include" else "EXCLUDED from the index"
        print(f"  WARNING: {stats['orphanCanonicalPages']} page(s) declare a canonical URL that has no page "
              f"(e.g. {sorted(inv.orphans)[0]}); {action}. Fix their <link rel=canonical> tags.")
    print(f"Search index written to {out_dir}")
    print(f"  entries : {t['entries']:,}  ({t['categoryPages']:,} category conversion pages + {t['explicitPages']} hand-built pages)")
    print(f"  units   : {t['units']:,} across {len(cat_info)} categories")
    print(f"  size    : {t['bytes']:,} bytes raw, {t['gzipBytes']:,} bytes gzip  (+ manifest {len(files['manifest.json']):,})")
    print(f"  version : {manifest['version']}")
    print(f"  excluded: {stats['excludedByReason']}  orphan-canonical pages: {stats['orphanCanonicalPages']} "
          f"(indexed: {stats['orphanCanonicalsIndexed']})")
    print(f"  verified: index expands to exactly the {len(on_disk):,} canonical pages found on disk "
          f"({time.time() - t0:.0f}s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
