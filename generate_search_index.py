#!/usr/bin/env python3
"""
generate_search_index.py - build the static, sharded search index used by the
site-wide search box (homepage + every page that loads app.js).

WHY THIS EXISTS
---------------
The previous index (one flat search-index.json) was built only from
seo-conversion-registry.json, which lists ~7.5k of the ~327k published pages.
Whole categories that were generated by other scripts (speed, density,
flow-rate, ...) were never in it, so a query such as "knots" had nothing to
match and the UI printed "No matching conversion found".

This generator derives the index from the pages that actually exist.  It
reuses generate_sitemaps.collect_inventory(), i.e. exactly the rules that
decide what goes into sitemap.xml:

    * pages marked noindex                       -> not indexed
    * meta-refresh redirect stubs                -> not indexed
    * pages whose <link rel=canonical> points
      at ANOTHER EXISTING page (duplicates)      -> not indexed

"Orphan canonicals" (a page whose canonical points at a URL for which no file
exists, e.g. area/acres-to-square-feet/ declaring /acres-to-square-feet/) are
a special case: the page itself is live (HTTP 200) and nothing else represents
it, while its canonical target would 404.  The default is to index such a page
under the URL it is really served at and to report the count loudly, so whole
categories (all of temperature/ today) do not vanish from search because of a
canonical-tag bug.  Use --orphan-canonicals exclude for the strict behaviour.
Once the canonical tags are fixed these pages become ordinary and nothing
changes here.

Every remaining page is then verified: the index is expanded again and the set
of URLs it yields must equal the set of canonical URLs found on disk.  The
build fails otherwise, so the index cannot contain a URL that has no page and
cannot silently miss one.

OUTPUT (static JSON, GitHub-Pages friendly, no backend)
-------------------------------------------------------
    search-index/manifest.json     version, category list, counts, sizes
    search-index/units.json        every unit: slug, name, symbol, aliases, tier
    search-index/pages.json        the hand-built pages: home, category hubs,
                                   popular root conversions (/kg-to-lbs/ ...),
                                   guides and tools
    search-index/pairs/<cat>.json  one shard per category: a bitmap saying which
                                   "<from>-to-<to>" pages exist

A category conversion page URL is  /<category>/<fromSlug>-to-<toSlug>/ , so the
~327k pages are described by ~2k unit records plus n*n bits per category
(about 45 KB of bitmaps in total) instead of ~327k repeated records.  The
browser loads units.json + pages.json on first use and a pair shard only when
a matched unit lives in that category.

USAGE
-----
    python3 generate_search_index.py            # (re)write search-index/
    python3 generate_search_index.py --check    # fail if the committed files are stale
    python3 generate_search_index.py --orphan-canonicals exclude
                                                # strict: leave out pages whose canonical has no file
                                                # (default: include them under their served URL)

build.py runs this with no arguments before copying the site into dist/.
"""

