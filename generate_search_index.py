# --------------------------------------------------------------------------
# small text helpers
# --------------------------------------------------------------------------

def singularize(word: str) -> str:
    if word in IRREGULAR_SINGULARS:
        return IRREGULAR_SINGULARS[word]
    if len(word) > 3 and word.endswith("ies"):
        return word[:-3] + "y"
    if len(word) > 4 and re.search(r"(ches|shes|sses|xes|zes)$", word):
        return word[:-2]
    if len(word) > 2 and word.endswith("s") and not word.endswith(("ss", "us", "is")):
        return word[:-1]
    return word


def unit_id_candidates(token: str) -> list[str]:
    """Slug token -> candidate curated-table ids ('kilometers-per-hour' -> kilometer_per_hour ...)."""
    base = token.replace("-", "_")
    words = base.split("_")
    cands = [base]
    if len(words) > 1:
        last = words[:-1] + [singularize(words[-1])]
        cands.append("_".join(last))
        first = [singularize(words[0])] + words[1:]
        cands.append("_".join(first))
    else:
        cands.append(singularize(base))
    out = []
    for c in cands:
        if c not in out:
            out.append(c)
    return out


def curated_for_token(token: str):
    """Return (aliases, keywords, tier) for a unit slug token."""
    for cand in unit_id_candidates(token):
        if cand in UNIT_ALIASES or cand in UNIT_KEYWORDS or cand in POPULAR_TIER:
            return (UNIT_ALIASES.get(cand, []), UNIT_KEYWORDS.get(cand, []),
                    POPULAR_TIER.get(cand, TIER_OTHER_CURATED))
    return [], [], TIER_DEFAULT


def title_words(slug: str) -> str:
    return " ".join(w[:1].upper() + w[1:] for w in slug.split("-") if w)


def clean_page_title(raw: str) -> str:
    t = re.sub(r"\s*[|\-–—]\s*Universal Converter\s*$", "", raw.strip())
    return re.sub(r"\s+", " ", t).strip()


def read_title(path: Path) -> str:
    try:
        with open(path, "rb") as fh:
            head = fh.read(TITLE_READ_BYTES)
    except OSError:
        return ""
    m = TITLE_TAG_RE.search(head)
    if not m:
        return ""
    import html as html_lib
    return re.sub(r"\s+", " ", html_lib.unescape(m.group(1).decode("utf-8", "replace"))).strip()


# --------------------------------------------------------------------------
# inventory -> classified pages
